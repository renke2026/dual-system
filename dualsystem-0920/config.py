@dataclass
class AblationConfig:
    # Decision-engine baseline (run.py --baseline):
    #   "full"      = dual-system (System-1 rules + System-2 LLM), default.
    #   "event_llm" = event-triggered LLM (no cognitive state machine).
    #   "mnl"       = conventional MNL discrete choice (fully non-LLM).
    baseline_mode: str = "full"

    # A. Event-triggered baseline: strip the cognitive-state mechanism,
    #    keep "event trigger + LLM decision" only.
    baseline_no_cognitive_state: bool = False

    # B. FSM / Pydantic constraint ablation.
    disable_pydantic_validation: bool = False
    disable_fsm_intercept: bool = False

    # C. Persona vs numeric-parameter ablation.
    uniform_persona: bool = False
    uniform_numeric_params: bool = False

    # Fixed persona used when uniform_persona=True.
    uniform_persona_role: str = "COMMUTER"
    uniform_persona_price_trait: str = "SENSITIVE"
    uniform_persona_anxiety_trait: str = "ANXIOUS"

    # Fixed numeric params used when uniform_numeric_params=True.
    uniform_anxiety_level: float = 0.5
    uniform_price_sensitivity: float = 0.5
    uniform_param_role: str = "COMMUTER"
    uniform_param_price_trait: str = "SENSITIVE"
    uniform_param_anxiety_trait: str = "ANXIOUS"

    # D. Memory ablation: True disables loading/retrieval/write/reflection.
    #    Default True (no memory); enable with `run.py --memory`.
    disable_memory: bool = True


@dataclass
class MNLConfig:
    # Utility: U_i = -beta_time*t_i - beta_price*p_i - beta_distance*d_i,
    #   where t_i = wait (min) + travel (distance/avg_speed*60).
    beta_time: float = 0.5        # time cost per minute
    beta_price: float = 30.0      # price cost per $/kWh
    beta_distance: float = 1.0    # distance cost per km
    anxiety_time_scale: float = 1.0         # beta_time *= (1 + anxiety * scale)
    price_sensitivity_scale: float = 1.0    # beta_price *= (1 + sensitivity * scale)
    avg_speed_kmh: float = 30.0   # assumed urban average speed (km/h)
    temperature: float = 1.0      # softmax temperature (lower = closer to argmax)


@dataclass
class Config:
    paths: PathConfig = field(default_factory=PathConfig)
    secrets: SecretsConfig = field(default_factory=SecretsConfig)
    simulation: SimulationConfig = field(default_factory=SimulationConfig)
    vehicle: VehicleConfig = field(default_factory=VehicleConfig)
    station: StationConfig = field(default_factory=StationConfig)
    grid: GridConfig = field(default_factory=GridConfig)
    solver: SolverConfig = field(default_factory=SolverConfig)
    agent: AgentConfig = field(default_factory=AgentConfig)
    npc: NPCConfig = field(default_factory=NPCConfig)
    memory: MemoryConfig = field(default_factory=MemoryConfig)
    storage: StorageConfig = field(default_factory=StorageConfig)
    llm: LLMConfig = field(default_factory=LLMConfig)
    generation: GenerationConfig = field(default_factory=GenerationConfig)
    pricing: PricingConfig = field(default_factory=PricingConfig)
    pipeline: PipelineConfig = field(default_factory=PipelineConfig)
    ablation: AblationConfig = field(default_factory=AblationConfig)
    mnl: MNLConfig = field(default_factory=MNLConfig)

    def describe(self) -> str:
        """Print the full current configuration (for experiment reproducibility)."""
        lines = ["=" * 70, "Current experiment configuration (CONFIG)", "=" * 70]
        for section in [
            "paths", "simulation", "vehicle", "station", "grid", "solver", "agent",
            "npc", "memory", "storage", "llm", "generation", "pipeline",
            "ablation", "mnl",
        ]:
            lines.append(f"\n[{section}]")
            sec = getattr(self, section)
            for k, v in sec.__dict__.items():
                lines.append(f"  {k} = {v!r}")
        lines.append("=" * 70)
        return "\n".join(lines)


CONFIG = Config()


def _apply_env_overrides():
    """Bridge command-line args (passed via DUALSYS_* env vars) into CONFIG."""
    def _int(name):
        v = os.environ.get(name)
        return int(v) if v is not None else None

    def _bool(name):
        v = os.environ.get(name)
        return (v == "1") if v is not None else None

    if os.environ.get("DUALSYS_CASE"):
        CONFIG.paths.case_name = os.environ.get("DUALSYS_CASE")
        CONFIG.paths.__post_init__()

    if _int("DUALSYS_DAYS") is not None:
        CONFIG.simulation.days = _int("DUALSYS_DAYS")
    if _bool("DUALSYS_GUI") is not None:
        CONFIG.simulation.sumo_gui = _bool("DUALSYS_GUI")
    if _int("DUALSYS_CONCURRENCY") is not None:
        CONFIG.simulation.max_api_concurrency = _int("DUALSYS_CONCURRENCY")
    if _int("DUALSYS_NPCS") is not None:
        CONFIG.generation.npcs_count = _int("DUALSYS_NPCS")
    if _int("DUALSYS_SEED") is not None:
        CONFIG.generation.agents_seed = _int("DUALSYS_SEED")
        CONFIG.generation.npcs_seed = _int("DUALSYS_SEED")
    if _int("DUALSYS_INSTANCES") is not None:
        CONFIG.generation.instances_per_archetype = _int("DUALSYS_INSTANCES")
    if _bool("DUALSYS_FORCE_NEW") is not None:
        CONFIG.generation.force_new_archetypes = _bool("DUALSYS_FORCE_NEW")
    if _bool("DUALSYS_NO_COG") is not None:
        CONFIG.ablation.baseline_no_cognitive_state = _bool("DUALSYS_NO_COG")
    if _bool("DUALSYS_NO_PYDANTIC") is not None:
        CONFIG.ablation.disable_pydantic_validation = _bool("DUALSYS_NO_PYDANTIC")
    if _bool("DUALSYS_NO_FSM") is not None:
        CONFIG.ablation.disable_fsm_intercept = _bool("DUALSYS_NO_FSM")
    if _bool("DUALSYS_UNIFORM_PERSONA") is not None:
        CONFIG.ablation.uniform_persona = _bool("DUALSYS_UNIFORM_PERSONA")
    if _bool("DUALSYS_UNIFORM_PARAMS") is not None:
        CONFIG.ablation.uniform_numeric_params = _bool("DUALSYS_UNIFORM_PARAMS")
    if _bool("DUALSYS_NO_MEMORY") is not None:
        CONFIG.ablation.disable_memory = _bool("DUALSYS_NO_MEMORY")

    bm = os.environ.get("DUALSYS_BASELINE")
    if bm:
        CONFIG.ablation.baseline_mode = bm
    if CONFIG.ablation.baseline_mode != "full":
        CONFIG.ablation.baseline_no_cognitive_state = True


_apply_env_overrides()


if __name__ == "__main__":
    print(CONFIG.describe())
