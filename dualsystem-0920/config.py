@dataclass
class PathConfig:
    case_name: str = DEFAULT_CASE

    # Paths below are populated in __post_init__ from CASE_REGISTRY.
    net_file: str = ""
    taz_file: str = ""
    type_file: str = ""
    station_file: str = ""   # generated by overwrite_prices.py
    grid_file: str = ""
    fcs_file: str = ""       # input when generating prices
    scs_file: str = ""       # input when generating prices
    agents_file: str = ""
    npcs_file: str = ""

    archetypes_file: str = str(CASE_DIR / "archetypes.json")
    results_dir: str = str(PROJECT_ROOT / "results")
    chroma_db: str = str(PROJECT_ROOT / "chroma_db")
    sumo_log: str = str(PROJECT_ROOT / "sumo_error.log")

    def __post_init__(self):
        info = CASE_REGISTRY.get(self.case_name)
        if info is None:
            raise ValueError(
                f"Unknown road network case: {self.case_name!r}, available: {sorted(CASE_REGISTRY)}"
            )
        for key, path in info.items():
            setattr(self, key, str(path))


